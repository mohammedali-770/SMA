#!/usr/bin/env node
/**
 * Generates the Google Play feature graphic from the brand mark.
 *
 * Play requires a feature graphic on every listing — 1024 x 500, PNG or JPEG,
 * at most 15 MB, and it must be fully opaque. Nothing in this repository was
 * that shape, so the store listing could not be completed
 * (`docs/OWNER_ACTIONS.md` §38, `docs/GO_LIVE_READINESS.md` G4).
 *
 * Generated rather than hand-exported for the same reason the store icon is: a
 * committed binary nobody can rebuild drifts from the brand the moment the
 * master changes, and `play-feature-graphic:check` catches that in CI.
 *
 * THREE DELIBERATE DESIGN CHOICES, each of which is a way to get it wrong:
 *
 * 1. NO TEXT. Play overlays the app name over this graphic on some surfaces,
 *    so baked-in text collides with it — and text would need a separate
 *    graphic per listing language. The default listing here is Arabic with
 *    English added, so a wordless mark serves both.
 * 2. GENEROUS MARGINS. The graphic is cropped at the edges on certain
 *    placements, so the mark occupies 76% of the height, centred, and nothing
 *    important goes near a boundary.
 * 3. FULLY OPAQUE. Play rejects transparency here. The mark is composited onto
 *    the brand red rather than left with an alpha channel.
 *
 * The resample is area-averaged in PREMULTIPLIED alpha. `logo-mark.png` has a
 * transparent surround, and averaging straight RGBA would drag the mark's
 * anti-aliased edges toward black — a grey halo on a red field.
 *
 * Pure Node; the PNG codec is `scripts/lib/png.mjs`, shared with the other two
 * asset generators.
 *
 * Usage: node scripts/build-play-feature-graphic.mjs [--check]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { decodePng, encodePng } from './lib/png.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The transparent-background brand mark, itself generated by build-logo-mark.mjs. */
const SOURCE = join(ROOT, 'assets/logo-mark.png');
const TARGET = join(ROOT, 'assets/store/play-feature-graphic-1024x500.png');

const WIDTH = 1024;
const HEIGHT = 500;
/** Play's ceiling for this asset. */
const MAX_BYTES = 15 * 1024 * 1024;
/**
 * Warm off-white, #F5F1E8 — the owner's choice from five rendered options, and
 * deliberately NOT a colour from the mark.
 *
 * The mark is only three colours: a white body, a red comb (#DE1124) and a navy
 * outline (#140560). Any of them as a backdrop erases the part of the artwork
 * that shares it. A near-neutral ground lets all three read at once: the navy
 * outline carries the silhouette against the cream, so the white body does not
 * need contrast of its own, and the red comb stays the focal point.
 *
 * The first version used the brand red, and it was wrong for a reason worth
 * recording rather than quietly fixing: #DE1124 was sampled from the centre of
 * the icon master, which is a methodical way to pick a colour and still gave the
 * worst result, because the comb and wattle are that exact red and vanished into
 * the background. A backdrop drawn from the palette has to be a colour the
 * artwork does not already use at its focal point — and here, that ruled out
 * every colour in the palette.
 */
const BACKDROP = [245, 241, 232];
/** Mark height as a fraction of the canvas — leaves margin for Play's cropping. */
const MARK_SCALE = 0.76;

/**
 * Area-average resample to an arbitrary size, in premultiplied alpha.
 *
 * Arbitrary rather than integer-factor (unlike the store icon, where 1024 -> 512
 * is exactly 2:1) because the mark is 885 px square and the target is derived
 * from the canvas height, so the ratio is never clean.
 */
function resample({ width, height, pixels }, dw, dh) {
  const out = Buffer.alloc(dw * dh * 4);
  const sx = width / dw;
  const sy = height / dh;

  for (let y = 0; y < dh; y++) {
    const y0 = Math.floor(y * sy);
    const y1 = Math.max(y0 + 1, Math.floor((y + 1) * sy));

    for (let x = 0; x < dw; x++) {
      const x0 = Math.floor(x * sx);
      const x1 = Math.max(x0 + 1, Math.floor((x + 1) * sx));

      let r = 0;
      let g = 0;
      let b = 0;
      let a = 0;
      let n = 0;

      for (let yy = y0; yy < y1; yy++) {
        for (let xx = x0; xx < x1; xx++) {
          const i = (yy * width + xx) * 4;
          const alpha = pixels[i + 3];
          r += pixels[i] * alpha;
          g += pixels[i + 1] * alpha;
          b += pixels[i + 2] * alpha;
          a += alpha;
          n++;
        }
      }

      const o = (y * dw + x) * 4;
      // Un-premultiply against the SUMMED alpha so the division cancels exactly;
      // the stored alpha is the mean over the sampled box.
      out[o] = a === 0 ? 0 : Math.round(r / a);
      out[o + 1] = a === 0 ? 0 : Math.round(g / a);
      out[o + 2] = a === 0 ? 0 : Math.round(b / a);
      out[o + 3] = Math.round(a / n);
    }
  }

  return { width: dw, height: dh, pixels: out };
}

const check = process.argv.includes('--check');

const mark = decodePng(readFileSync(SOURCE));
const size = Math.round(HEIGHT * MARK_SCALE);
const small = resample(mark, size, size);

const canvas = Buffer.alloc(WIDTH * HEIGHT * 4);
for (let i = 0; i < WIDTH * HEIGHT; i++) {
  canvas[i * 4] = BACKDROP[0];
  canvas[i * 4 + 1] = BACKDROP[1];
  canvas[i * 4 + 2] = BACKDROP[2];
  canvas[i * 4 + 3] = 0xff;
}

const ox = Math.round((WIDTH - size) / 2);
const oy = Math.round((HEIGHT - size) / 2);
for (let y = 0; y < size; y++) {
  for (let x = 0; x < size; x++) {
    const s = (y * size + x) * 4;
    const d = ((y + oy) * WIDTH + (x + ox)) * 4;
    const alpha = small.pixels[s + 3] / 255;
    if (alpha === 0) continue;
    for (let c = 0; c < 3; c++) {
      canvas[d + c] = Math.round(small.pixels[s + c] * alpha + canvas[d + c] * (1 - alpha));
    }
  }
}

// Asserted rather than assumed: a transparent pixel here is a Play rejection.
for (let i = 3; i < canvas.length; i += 4) {
  if (canvas[i] !== 0xff) throw new Error('feature graphic must be fully opaque');
}

const graphic = encodePng({ width: WIDTH, height: HEIGHT, pixels: canvas });

if (graphic.length > MAX_BYTES) {
  throw new Error(`generated graphic is ${graphic.length} bytes, over Play's ${MAX_BYTES} limit`);
}

let current = null;
try {
  current = readFileSync(TARGET);
} catch {
  /* not generated yet */
}

if (current && current.equals(graphic)) {
  if (check) console.log('✔ Play feature graphic is up to date');
  process.exit(0);
}

if (check) {
  console.error(`✖ ${TARGET} is out of date — run: node scripts/build-play-feature-graphic.mjs`);
  process.exit(1);
}

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, graphic);
console.log(`✔ wrote ${TARGET} (${WIDTH}x${HEIGHT}, ${graphic.length} bytes)`);
