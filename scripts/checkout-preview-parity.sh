#!/usr/bin/env bash
#
# Regenerate the checkout preview parity fixture from the REAL server functions.
#
#   bash scripts/checkout-preview-parity.sh            # rewrite the fixture and the suite's digest
#   bash scripts/checkout-preview-parity.sh --check    # regenerate in memory, fail on any drift
#
# WHAT IT DOES. It builds a throwaway database from the repository's own
# migration chain, exactly as .github/sql-ci/run.sh does (bootstrap.sql, every
# migration in filename order, harness.sql, seed.sql), then runs
# supabase/tests/checkout_preview_parity_test.sql in EMIT mode. That file prices
# a fixed table of carts with `compute_order_snapshot` (card) and `place_order`
# (cash), refuses if the two disagree, and prints every answer as JSON. This
# script writes that JSON to
# apps/mobile/src/features/checkout/previewParity.fixture.json, which
# previewParity.test.ts feeds to computePreviewTotals, and writes the answers'
# digest into the suite, which CI then checks against the server whenever a
# migration or a suite changes. Nothing it creates survives: the suite rolls
# back, and the database is dropped on exit.
#
# LOCAL ONLY. It creates and drops a database, so it refuses any PGHOST that is
# not this machine (CLAUDE.md §10: harnesses use disposable local databases).
#
# Needs: psql, createdb and dropdb; node; and the root `npm ci` (for Prettier,
# which the format check holds a new JSON file to).
#
# Environment:
#   PGHOST, PGPORT, PGUSER, PGPASSWORD   a local PostGIS Postgres (16, like CI)
#   PGDATABASE      the admin database to connect to first (default postgres)
#   PARITY_DB       the throwaway database (default sma_preview_parity). It must
#                   contain "preview_parity", so a typo cannot drop a real one.
#   PARITY_TEMPLATE optional: an existing database already built from THIS tree
#                   (for example the template .github/sql-ci/run.sh leaves
#                   behind) to clone instead of replaying the chain, which takes
#                   minutes. It is only read.

set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SQL_CI="$ROOT/.github/sql-ci"
SUITE="$ROOT/supabase/tests/checkout_preview_parity_test.sql"
FIXTURE="$ROOT/apps/mobile/src/features/checkout/previewParity.fixture.json"
PRETTIER="$ROOT/node_modules/.bin/prettier"
PARITY_DB="${PARITY_DB:-sma_preview_parity}"
PARITY_TEMPLATE="${PARITY_TEMPLATE:-}"

CHECK=0
case "${1:-}" in
  --check) CHECK=1 ;;
  '') ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

case "${PGHOST:-localhost}" in
  localhost|127.0.0.1|::1|/*) ;;
  *) echo "refusing: PGHOST=${PGHOST} is not a local database" >&2; exit 2 ;;
esac
case "$PARITY_DB" in
  *preview_parity*) ;;
  *) echo "refusing: PARITY_DB=$PARITY_DB must contain 'preview_parity'" >&2; exit 2 ;;
esac
if [ -n "$PARITY_TEMPLATE" ] && [ "$PARITY_TEMPLATE" = "$PARITY_DB" ]; then
  echo "refusing: PARITY_TEMPLATE and PARITY_DB are the same database" >&2
  exit 2
fi
if [ ! -x "$PRETTIER" ]; then
  echo "Prettier is not installed: run npm ci at the repository root first" >&2
  exit 2
fi

WORK="$(mktemp -d)"
cleanup() {
  dropdb --if-exists "$PARITY_DB" >/dev/null 2>&1 || true
  rm -rf "$WORK"
}
trap cleanup EXIT

psql_on() { psql -X -q -v ON_ERROR_STOP=1 --no-align --tuples-only -d "$1" "${@:2}"; }

dropdb --if-exists "$PARITY_DB" >/dev/null 2>&1
if [ -n "$PARITY_TEMPLATE" ]; then
  createdb -T "$PARITY_TEMPLATE" "$PARITY_DB"
  echo "cloned $PARITY_TEMPLATE into $PARITY_DB"
else
  createdb "$PARITY_DB"
  psql_on "$PARITY_DB" -f "$SQL_CI/bootstrap.sql" >/dev/null
  n=0
  while IFS= read -r f; do
    n=$((n + 1))
    if ! psql_on "$PARITY_DB" -f "$f" >/dev/null 2>"$WORK/err"; then
      echo "migration chain failed at $(basename "$f"):" >&2
      cat "$WORK/err" >&2
      exit 1
    fi
  done < <(find "$ROOT/supabase/migrations" -maxdepth 1 -name '*.sql' | sort)
  psql_on "$PARITY_DB" -f "$SQL_CI/harness.sql" >/dev/null
  psql_on "$PARITY_DB" -f "$ROOT/supabase/seed.sql" >/dev/null
  echo "built $PARITY_DB from $n migrations"
fi

psql_on "$PARITY_DB" -v parity_emit=1 -f "$SUITE" >"$WORK/raw.json"

MIGRATIONS="$(find "$ROOT/supabase/migrations" -maxdepth 1 -name '*.sql' | wc -l | tr -d ' ')"
LATEST="$(basename "$(find "$ROOT/supabase/migrations" -maxdepth 1 -name '*.sql' | sort | tail -n 1)")"

node - "$WORK/raw.json" "$WORK/fixture.json" "$MIGRATIONS" "$LATEST" <<'NODE'
const { readFileSync, writeFileSync } = require('node:fs');
const [raw, out, migrations, latest] = process.argv.slice(2);
const server = JSON.parse(readFileSync(raw, 'utf8'));
if (!/^[0-9a-f]{32}$/.test(server.digest || '') || !Array.isArray(server.cases) || !server.cases.length) {
  console.error('the suite emitted no digest or no carts');
  process.exit(1);
}
const fixture = {
  $comment: [
    'GENERATED by scripts/checkout-preview-parity.sh. Do not edit by hand.',
    'Each "server" block is what compute_order_snapshot answered for that cart, on a local database',
    'built from the migration chain in "generatedFrom". place_order agreed on every amount: the suite',
    'that produced this refuses otherwise.',
  ],
  generatedFrom: {
    suite: 'supabase/tests/checkout_preview_parity_test.sql',
    migrations: Number(migrations),
    latestMigration: latest,
    functionDefMd5: server.functions,
  },
  digest: server.digest,
  branch: server.branch,
  cases: server.cases,
};
writeFileSync(out, JSON.stringify(fixture, null, 2) + '\n');
NODE
"$PRETTIER" --config "$ROOT/.prettierrc.json" --log-level warn --write "$WORK/fixture.json" >/dev/null

if [ "$CHECK" -eq 1 ]; then
  node - "$FIXTURE" "$WORK/fixture.json" "$SUITE" <<'NODE'
const { readFileSync } = require('node:fs');
const [committedPath, freshPath, suitePath] = process.argv.slice(2);
const committed = JSON.parse(readFileSync(committedPath, 'utf8'));
const fresh = JSON.parse(readFileSync(freshPath, 'utf8'));
const pick = (f) => JSON.stringify({ digest: f.digest, branch: f.branch, cases: f.cases });
let drift = false;
if (pick(committed) !== pick(fresh)) {
  console.error('DRIFT: the committed fixture no longer matches what the server answers.');
  console.error(`  committed digest ${committed.digest}, server now ${fresh.digest}`);
  drift = true;
}
const line = `\\set parity_expected_digest '${fresh.digest}'`;
if (!readFileSync(suitePath, 'utf8').split('\n').includes(line)) {
  console.error(`DRIFT: the suite does not carry the digest ${fresh.digest}.`);
  drift = true;
}
if (drift) {
  console.error('  Run: bash scripts/checkout-preview-parity.sh');
  process.exit(1);
}
console.log(`parity fixture is current (digest ${fresh.digest})`);
NODE
  exit 0
fi

node - "$WORK/fixture.json" "$FIXTURE" "$SUITE" <<'NODE'
const { readFileSync, writeFileSync } = require('node:fs');
const [freshPath, fixturePath, suitePath] = process.argv.slice(2);
const fresh = readFileSync(freshPath, 'utf8');
const { digest } = JSON.parse(fresh);
const suite = readFileSync(suitePath, 'utf8');
const pattern = /^\\set parity_expected_digest '[0-9a-f]{32}'$/m;
if (!pattern.test(suite)) {
  console.error(`no "\\set parity_expected_digest '<md5>'" line in ${suitePath}`);
  process.exit(1);
}
writeFileSync(suitePath, suite.replace(pattern, `\\set parity_expected_digest '${digest}'`));
writeFileSync(fixturePath, fresh);
console.log(`wrote the fixture and the digest ${digest}`);
NODE
